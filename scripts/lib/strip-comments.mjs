/**
 * strip-comments — 契约测试里「只看真代码,不看注释」的那一步(2026-07-29)。
 *
 * 16 条契约测试各自复制了同一行剥注释的正则,它有个洞:
 * **字符串里的「斜杠星号」也被算成注释起点**。
 *
 * 实锤:NesioChatSheet.tsx 里有一句 accept = image 斜杠星号(文件选择器的 MIME 通配),
 * 那个记号让正则一路吃到下一个「星号斜杠」,一口气吞掉 10086 个字符 ——
 * 整整 80KB 的文件被剥成 59KB。后果是**静默的**:对那段代码的断言全都在一份
 * 看不见它的文本上跑,「没有匹配」被当成「没有违规」,于是恒绿。
 * 发现它纯属偶然 —— 一条新写的断言数不出该有的 4 个调用点,才顺着查出来。
 *
 * 修法:要求注释起点前面不是单词字符,也不是引号。真注释前面总是空白、花括号(JSX)
 * 或行首;而 image 斜杠星号 里那个前面是字母 e,被引号包起来的那个前面是引号。
 * 这挡不住所有构造(比如变量名后紧跟除法再跟乘法),但挡住了实际会出现的那些。
 *
 * ⚠️ 这段说明里**不能出现**注释结束记号的字面写法 —— 会把这段注释自己提前关掉。
 * 写第一版时就踩了:那一行里带了个字面记号,整个模块当场语法错误。
 * 一个防「记号被误当注释」的模块,自己先栽在同一件事上。
 *
 * 契约:scripts/strip-comments.test.mjs。
 */

/** 剥掉块注释和整行的 `//` 注释,保留字符串里长得像注释的东西。 */
export function stripComments(src) {
  return src
    .replace(/(?<![\w'"`])\/\*[\s\S]*?\*\//g, '')
    .replace(/^\s*\/\/.*$/gm, '');
}
