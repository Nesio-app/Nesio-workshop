/**
 * chat-internal-text — 认出「这句话是说给程序听的,不是说给人听的」(2026-07-29 QA #17)。
 *
 * 用户翻念念的历史对话,看到它自己说过:
 *   「识别到:未检测到任何生命图谱条目」
 *   「识别到:用户未提供任何输入信息,无法提取生命图谱节点」
 * 这是内部诊断被原样当成回复发出去了。
 *
 * **产生这种话的三个入口 2026-07-28/29 都已经修好**(NesioChatSheet:436/598/947,
 * 现在没认出来就直说「这张图没看清」)。但已经发生的对话**存在 localStorage 里**,
 * 每次打开历史照样再显示一遍 —— 修了源头不等于修了现场。这一层管现场。
 *
 * 判据是「内部词汇」而不是「那两句原话」:
 * 「生命图谱」「节点」「条目」是数据模型的说法,产品里从来不该出现在给用户的句子中。
 * 照原话匹配只能挡住这两句,下一句换个说法就漏。
 *
 * 只读不写:在渲染那一层换掉,不去改用户的历史数据 —— 万一判重了,原文还在。
 *
 * 契约:scripts/chat-internal-text.test.mjs。
 */

/** 内部数据模型的词汇。命中任一 = 这句话没打算给人看。 */
const INTERNAL_MARKERS: RegExp[] = [
  /生命图谱/,
  /life[\s_-]?graph/i,
  /未提供任何输入信息/,
  /无法提取[^。\n]{0,8}节点/,
  /未检测到任何[^。\n]{0,8}(条目|节点)/,
  /\b(null|undefined|NaN)\b\s*$/,
];

/**
 * 这条模型回复是内部诊断吗?
 *
 * 只判模型说的话 —— 用户自己完全可以打「生命图谱」这四个字问问题,
 * 那是正常提问,不该被换掉。调用方负责只对 role === 'model' 的气泡用它。
 */
export function isInternalDiagnostic(text: string): boolean {
  const s = (text || '').trim();
  if (!s) return false;
  return INTERNAL_MARKERS.some((re) => re.test(s));
}
