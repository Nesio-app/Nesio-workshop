/**
 * chat-markdown — 把模型回复里的 markdown 记号变成能读的纯文本(2026-07-29 QA #18)。
 *
 * 聊天气泡是 `<p>{msg.text}</p>`,纯文本渲染。而模型很自然地会用 markdown 列表回答
 * 「我这周有什么日程」,于是用户看到的是:
 *   * 7月28日（周二）
 *   **重要**：下午三点开会
 * 星号原样糊在正文里。
 *
 * 这里**不渲染 HTML** —— 聊天内容里混着邮件正文、日程标题这些外部数据,
 * 把它当 HTML 渲染等于开一个注入口子。只做记号 → 可读字符的替换,输出仍是纯文本。
 *
 * 契约:scripts/chat-markdown.test.mjs。
 */

export function markdownToPlain(input: string): string {
  const raw = String(input || '');
  if (!raw) return '';
  return raw
    .split('\n')
    .map((line) => {
      let s = line;
      // 行首的列表记号 → 圆点(保留缩进,嵌套层次还看得出来)
      s = s.replace(/^(\s*)[*+-]\s+/, '$1• ');
      // 行首的标题记号:去掉 # 本身,标题文字留着
      s = s.replace(/^(\s*)#{1,6}\s+/, '$1');
      // 行首引用记号
      s = s.replace(/^(\s*)>\s?/, '$1');
      return s;
    })
    .join('\n')
    // 粗体/斜体/删除线的成对记号 —— 只脱记号,不动内容
    .replace(/\*\*([^*\n]+)\*\*/g, '$1')
    .replace(/__([^_\n]+)__/g, '$1')
    .replace(/(^|[\s(])\*([^*\n]+)\*(?=[\s).,，。:：!?！？]|$)/g, '$1$2')
    .replace(/~~([^~\n]+)~~/g, '$1')
    // 行内代码:反引号去掉,内容留着(模型常拿它标字段名)
    .replace(/`([^`\n]+)`/g, '$1')
    // [文字](链接) → 文字(链接);裸链接不动,气泡里能直接看见
    .replace(/\[([^\]\n]+)\]\((https?:\/\/[^)\s]+)\)/g, '$1($2)')
    // 分隔线整行 → 删掉(气泡里画一条 --- 只是噪音)
    .replace(/^\s*([-*_]\s*){3,}$/gm, '')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}
