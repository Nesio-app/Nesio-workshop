export function getModuleCapabilityContract(moduleId, routeOrigin = 'local') {
  const capability = MODULE_CAPABILITIES[moduleId] || DEFAULT_CAPABILITIES;
  const mode = capability.mode || (routeOrigin === 'external' ? 'external' : 'local');

  return {
    mode,
    ownedData: [...capability.ownedData],
    consumedData: [...capability.consumedData],
    emittedEvents: [...capability.emittedEvents],
    allowedActions: [...capability.allowedActions],
    approvalRequiredActions: [...capability.approvalRequiredActions],
  };
}

export function buildModuleRegistry(config, options = {}) {
  const basePath = options.basePath || '';
  const shellReturnHref = options.returnHref || `${basePath || ''}/`;
  const toolManifest = buildToolManifestRegistryV0(config, {
    basePath,
    returnHref: shellReturnHref,
    capabilityForTool: getModuleCapabilityContract,
  });
  const manifestByModuleId = new Map(toolManifest.manifests.map((manifest) => [manifest.moduleId, manifest]));
  const modules = config.tools.map((tool) => {
    const route = getModuleRouteContract(tool.url, basePath);
    const manifest = manifestByModuleId.get(tool.id);
    const capabilities = {
      mode: getModuleCapabilityContract(tool.id, route.origin).mode,
      ownedData: [...(manifest?.ownedData || [])],
      consumedData: [...(manifest?.consumedData || [])],
      emittedEvents: [...(manifest?.emittedEvents || [])],
      allowedActions: [...(manifest?.allowedActions || [])],
      approvalRequiredActions: [...(manifest?.approvalRequiredActions || [])],
    };

    return {
      id: tool.id,
      name: tool.name,
      nameEn: tool.nameEn,
      description: tool.description,
      url: tool.url,
      zone: tool.zone,
      hotkey: tool.hotkey,
      command: tool.command,
      featured: tool.featured,
      icon: tool.icon,
      iconUrl: tool.iconUrl,
      ready: tool.ready === true,
      status: tool.status,
      integrationMode: tool.integrationMode,
      owner: tool.owner,
      maintainer: tool.maintainer,
      responsibleAgent: tool.responsibleAgent,
      evidenceOwner: tool.evidenceOwner,
      gateOwner: tool.gateOwner,
      origin: route.origin,
      routeKind: route.routeKind,
      configuredUrl: route.configuredUrl,
      normalizedPath: route.normalizedPath,
      openHref: route.openHref,
      returnHref: route.returnHref || shellReturnHref,
      publicIndexPath: route.publicIndexPath,
      toolManifest: manifest,
      toolLifecycle: manifest?.toolLifecycle,
      launchStatus: manifest?.launchStatus,
      prodExposure: manifest?.prodExposure,
      dataNamespace: manifest?.dataNamespace,
      dataContract: tool.dataContract,
      entitlementPolicy: manifest?.entitlementPolicy,
      mobileStrategy: manifest?.mobileStrategy,
      deprecationPolicy: manifest?.deprecationPolicy,
      capabilities,
      ownedData: capabilities.ownedData,
      consumedData: capabilities.consumedData,
      emittedEvents: capabilities.emittedEvents,
      allowedActions: capabilities.allowedActions,
      approvalRequiredActions: capabilities.approvalRequiredActions,
    };
  });

  return {
    shell: {
      name: config.meta?.title || 'Nesio',
      returnHref: shellReturnHref,
    },
    dataKeyOwnership: MODULE_DATA_KEY_OWNERSHIP_V1,
    experienceServices: EXPERIENCE_SERVICES_V0,
    dataAggregation: DATA_AGGREGATION_V0,
    approvalGate: APPROVAL_GATE_V0,
    shellRouteContract: SHELL_ROUTE_CONTRACT_V0,
    artifactVisibility: ARTIFACT_VISIBILITY_REGISTRY_V1,
    artifactStatusVisibility: ARTIFACT_STATUS_VISIBILITY_V02,
    shellDiscoveryEntrySlice: SHELL_DISCOVERY_ENTRY_SLICE_V0,
    mobileAppIntegration: MOBILE_APP_INTEGRATION_V0,
    toolManifest,
    modules,
  };
}
