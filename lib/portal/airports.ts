/** 三字码 → 机场真名+坐标;不认识返回 null(保持原样,不硬猜)。 */
export function resolveAirport(code: string): AirportPlace | null {
  const c = (code || '').trim();
  // 只认全大写三字码约定 ——「Kef」(首字母大写)是城市写法,不硬猜成机场
  if (!/^[A-Z]{3}$/.test(c)) return null;
  const hit = AIRPORTS[c];
  if (!hit) return null;
  return { label: `${hit[0]} (${c})`, labelEn: `${hit[1]} (${c})`, lat: hit[2], lon: hit[3], code: c };
}
